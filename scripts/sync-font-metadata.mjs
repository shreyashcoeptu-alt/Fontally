/**
 * Sync Google Fonts metadata (language subsets, variable axes, popularity) for
 * every family Fontally uses into shared/font-metadata.js.
 *
 *   npm run sync-fonts                 (downloads from fonts.google.com)
 *   npm run sync-fonts -- ./meta.json  (uses a local copy of the same JSON)
 *
 * Source: https://fonts.google.com/metadata/fonts, the public JSON that powers
 * fonts.google.com. It needs no API key. It is not a versioned API, so the app
 * never calls it at runtime: run this script when fonts or profiles change and
 * commit the output.
 *
 * Exits non-zero if a profile or catalog family does not exist on Google Fonts
 * (that is how "Geist Sans", really "Geist", slipped through before).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { profiles } from '../shared/profiles.js'
import { BODY_FONT_CANDIDATES } from '../shared/body-fonts.js'
import { ENRICHED_FONT_CATALOG } from '../server/lib/font-catalog.mjs'

const SOURCE_URL = 'https://fonts.google.com/metadata/fonts'
const OUT_FILE = new URL('../shared/font-metadata.js', import.meta.url)

const primaryFamily = (stack) => String(stack || '').split(',')[0].replace(/['"]/g, '').trim()

async function loadSource(localPath) {
  const text = localPath
    ? readFileSync(localPath, 'utf8')
    : await (await fetch(SOURCE_URL, { signal: AbortSignal.timeout(30_000) })).text()
  // Google prefixes some JSON responses with )]}' to block JSON hijacking
  return JSON.parse(text.replace(/^\)\]\}'\s*/, ''))
}

const CATEGORY = {
  'Sans Serif': 'sans-serif',
  Serif: 'serif',
  Display: 'display',
  Monospace: 'monospace',
  Handwriting: 'handwriting'
}

async function main() {
  const source = await loadSource(process.argv[2])
  const byFamily = new Map(source.familyMetadataList.map((f) => [f.family, f]))

  const wanted = new Set([
    ...profiles.flatMap((p) => [primaryFamily(p.headingFallback), primaryFamily(p.bodyFallback)]),
    ...ENRICHED_FONT_CATALOG.map((f) => f.family),
    ...BODY_FONT_CANDIDATES
  ])

  const families = {}
  const missing = []
  for (const name of [...wanted].sort()) {
    const f = byFamily.get(name)
    if (!f) {
      missing.push(name)
      continue
    }
    const weights = Object.keys(f.fonts || {}).filter((k) => /^\d+$/.test(k)).map(Number)
    families[name] = {
      category: CATEGORY[f.category] || String(f.category || '').toLowerCase(),
      subsets: (f.subsets || []).filter((s) => s !== 'menu'),
      axes: (f.axes || []).map(({ tag, min, max }) => ({ tag, min, max })),
      weights: weights.sort((a, b) => a - b),
      italic: Object.keys(f.fonts || {}).some((k) => k.endsWith('i')),
      // Rank on fonts.google.com: 1 = most popular
      popularity: f.popularity ?? null
    }
  }

  // A JS module (not .json) so Node and the Vite bundle import it the same way
  const banner = `// Generated by scripts/sync-font-metadata.mjs from fonts.google.com/metadata/fonts on ${new Date().toISOString().slice(0, 10)}.\n// Do not edit by hand: run \`npm run sync-fonts\`.\n`
  writeFileSync(OUT_FILE, `${banner}export const FONT_METADATA = ${JSON.stringify(families)}\n`)
  console.log(`Wrote ${Object.keys(families).length} families to shared/font-metadata.js`)

  if (missing.length) {
    console.error(`\n${missing.length} families are not on Google Fonts (fix their names):\n  ${missing.join('\n  ')}`)
    process.exitCode = 1
  }
}

main().catch((err) => {
  console.error('Font metadata sync failed:', err)
  process.exit(1)
})
