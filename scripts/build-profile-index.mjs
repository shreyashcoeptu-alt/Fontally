/**
 * Builds the profile vector index used for instant, embedding-based recommendations.
 *
 *   npm run build-index               # both steps (needs GEMINI_API_KEY in .env)
 *   npm run build-index -- --briefs   # only generate missing synthetic briefs
 *   npm run build-index -- --embed    # only (re)embed
 *   EMBED_DIMS=256 npm run build-index -- --embed
 *
 * Step 1 (briefs): asks Gemini for short, varied example briefs per profile
 *   ("doc2query"), saved to shared/profile-descriptors.json. Resumable: profiles
 *   that already have briefs are skipped, so hand edits survive re-runs.
 *   Gemini never sees tests/eval/briefs.json, so the held-out paraphrase set
 *   stays an honest test.
 * Step 2 (embed): embeds one descriptor + every example brief per profile
 *   (RETRIEVAL_DOCUMENT) -> server/data/profile-vectors.json, and the eval briefs
 *   (RETRIEVAL_QUERY) -> tests/eval/brief-vectors.json so CI can score retrieval
 *   offline without an API key.
 */
import 'dotenv/config'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { profiles } from '../shared/profiles.js'
import { primaryFamily } from '../shared/pairing.js'
import { encodeVector } from '../server/lib/vector-codec.mjs'

const API_BASE = 'https://generativelanguage.googleapis.com/v1beta/models'
const apiKey = process.env.GEMINI_API_KEY
const GEN_MODEL = process.env.GEMINI_MODEL || 'gemini-3.1-flash-lite'
const EMBED_MODEL = 'gemini-embedding-001'
const EMBED_DIMS = Number(process.env.EMBED_DIMS) || 768
const BRIEFS_PER_PROFILE = 12
const PROFILES_PER_REQUEST = 8

// Every embedding is checkpointed here (gitignored), so a run that hits the
// free tier's 1,000 embeds/day cap resumes where it stopped instead of starting over.
const EMBED_CACHE_FILE = '.cache/embeddings.json'
const DESCRIPTORS_FILE = 'shared/profile-descriptors.json'
const INDEX_FILE = 'server/data/profile-vectors.json'
const EVAL_BRIEFS_FILE = 'tests/eval/briefs.json'
const EVAL_VECTORS_FILE = 'tests/eval/brief-vectors.json'

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const readJson = (file, fallback) => (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : fallback)
const writeJson = (file, data) => {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, JSON.stringify(data, null, 2) + '\n')
}

if (!apiKey) {
  console.error('GEMINI_API_KEY is not set. Add it to .env.')
  process.exit(1)
}

/** POST with retries on 429/503, honouring Gemini's "retry in Ns". */
async function geminiPost(path, body) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`${API_BASE}/${path}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'x-goog-api-key': apiKey },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(60_000)
    })
    const payload = await res.json().catch(() => ({}))
    if (res.ok) return payload
    const message = (payload?.error?.message || '').split('\n')[0]
    if (/per day/i.test(JSON.stringify(payload?.error?.details || ''))) {
      throw new Error(`Daily free-tier quota reached (${message}). Progress is saved; re-run after the quota resets (midnight Pacific).`)
    }
    if ((res.status === 429 || res.status === 503) && attempt < 6) {
      const wait = Number(/retry in ([\d.]+)s/i.exec(message)?.[1])
      const ms = Number.isFinite(wait) ? Math.ceil(wait * 1000) + 1000 : 15_000 * attempt
      process.stdout.write(`  (${res.status}, waiting ${Math.round(ms / 1000)}s)\n`)
      await sleep(ms)
      continue
    }
    throw new Error(`HTTP ${res.status}: ${message}`)
  }
}

/** What a profile is, in words, for both the generator prompt and the descriptor vector. */
function describeProfile(p) {
  const heading = primaryFamily(p.headingFallback, p.name)
  const body = primaryFamily(p.bodyFallback, p.pair)
  return [
    `${p.archetype}.`,
    `Heading font ${heading} (${p.meta}), body font ${body}.`,
    p.rationale,
    `Fits: ${(p.words || []).join(', ')}.`
  ].join(' ')
}

// ---------------------------------------------------------------------------
// Step 1: synthetic briefs
// ---------------------------------------------------------------------------
async function generateBriefs() {
  const store = readJson(DESCRIPTORS_FILE, {
    _about: 'Example design briefs per profile, generated by scripts/build-profile-index.mjs and safe to hand-edit. They are embedded into server/data/profile-vectors.json. Never copy briefs from tests/eval/briefs.json here.',
    profiles: {}
  })
  const missing = profiles.filter((p) => !store.profiles[p.id]?.length)
  console.log(`Briefs: ${profiles.length - missing.length}/${profiles.length} profiles done, ${missing.length} to generate with ${GEN_MODEL}.`)

  for (let i = 0; i < missing.length; i += PROFILES_PER_REQUEST) {
    const batch = missing.slice(i, i + PROFILES_PER_REQUEST)
    const prompt = [
      'You help build a typography recommender. For EACH typography profile below, write',
      `${BRIEFS_PER_PROFILE} short design briefs (6 to 20 words) that a client might type, for which this profile is a great fit.`,
      'Rules:',
      '- Vary them: different industries, audiences, products, moods, places and phrasings.',
      '- At least half must NOT use any of the profile\'s listed keywords; describe the situation instead',
      '  (e.g. instead of "coffee shop": "a spot where commuters grab a flat white").',
      '- Include a few that are mood-only ("feels expensive but quiet") and a few with a brand name.',
      '- Never mention font names, typography terms, or the profile id.',
      '',
      'PROFILES:',
      JSON.stringify(batch.map((p) => ({ id: p.id, description: describeProfile(p) })))
    ].join('\n')

    const payload = await geminiPost(`${encodeURIComponent(GEN_MODEL)}:generateContent`, {
      contents: [{ role: 'user', parts: [{ text: prompt }] }],
      generationConfig: {
        temperature: 1,
        responseMimeType: 'application/json',
        responseSchema: {
          type: 'object',
          properties: {
            profiles: {
              type: 'array',
              items: {
                type: 'object',
                properties: { id: { type: 'string' }, briefs: { type: 'array', items: { type: 'string' } } },
                required: ['id', 'briefs']
              }
            }
          },
          required: ['profiles']
        },
        ...(/gemini-[3-9]/.test(GEN_MODEL) ? { thinkingConfig: { thinkingLevel: 'minimal' } } : {})
      }
    })
    const text = payload?.candidates?.[0]?.content?.parts?.map((part) => part.text || '').join('') || '{}'
    const wanted = new Set(batch.map((p) => p.id))
    for (const entry of JSON.parse(text).profiles || []) {
      if (!wanted.has(entry.id)) continue
      const briefs = [...new Set((entry.briefs || []).map((b) => String(b).trim()).filter((b) => b.length >= 8 && b.length <= 200))]
      if (briefs.length) store.profiles[entry.id] = briefs.slice(0, BRIEFS_PER_PROFILE)
    }
    writeJson(DESCRIPTORS_FILE, store) // save after every batch so a crash loses nothing
    const done = profiles.filter((p) => store.profiles[p.id]?.length).length
    console.log(`  batch ${i / PROFILES_PER_REQUEST + 1}: ${done}/${profiles.length} profiles have briefs`)
    if (i + PROFILES_PER_REQUEST < missing.length) await sleep(13_000) // free tier: 5 req/min
  }

  const stillMissing = profiles.filter((p) => !store.profiles[p.id]?.length).map((p) => p.id)
  if (stillMissing.length) console.warn(`Still missing briefs (re-run to retry): ${stillMissing.join(', ')}`)
}

// ---------------------------------------------------------------------------
// Step 2: embeddings
// ---------------------------------------------------------------------------
async function embedAll(texts, taskType) {
  const cache = readJson(EMBED_CACHE_FILE, {})
  const keyOf = (text) => `${EMBED_MODEL}|${EMBED_DIMS}|${taskType}|${text}`
  const todo = [...new Set(texts.filter((t) => !cache[keyOf(t)]))]
  console.log(`  ${texts.length - todo.length}/${texts.length} already cached, ${todo.length} to embed`)
  for (let i = 0; i < todo.length; i += 100) {
    const chunk = todo.slice(i, i + 100)
    const payload = await geminiPost(`${EMBED_MODEL}:batchEmbedContents`, {
      requests: chunk.map((text) => ({
        model: `models/${EMBED_MODEL}`,
        content: { parts: [{ text }] },
        taskType,
        outputDimensionality: EMBED_DIMS
      }))
    })
    const vectors = (payload.embeddings || []).map((e) => e.values)
    if (vectors.length !== chunk.length) throw new Error(`Expected ${chunk.length} embeddings, got ${vectors.length}`)
    chunk.forEach((text, j) => { cache[keyOf(text)] = encodeVector(vectors[j]) })
    writeJson(EMBED_CACHE_FILE, cache)
    process.stdout.write(`  ${Math.min(i + 100, todo.length)}/${todo.length}\n`)
    if (i + 100 < todo.length) await sleep(4_000)
  }
  return texts.map((t) => cache[keyOf(t)])
}

async function embed() {
  const store = readJson(DESCRIPTORS_FILE, { profiles: {} })
  const rows = []
  for (const p of profiles) {
    rows.push({ id: p.id, text: describeProfile(p) })
    for (const brief of store.profiles[p.id] || []) rows.push({ id: p.id, text: brief })
  }
  console.log(`Embedding ${rows.length} profile texts (${EMBED_MODEL}, ${EMBED_DIMS} dims)...`)
  const vectors = await embedAll(rows.map((r) => r.text), 'RETRIEVAL_DOCUMENT')

  const index = {}
  rows.forEach((row, i) => (index[row.id] ||= []).push(vectors[i]))
  writeJson(INDEX_FILE, {
    _about: 'Generated by `npm run build-index`. Do not edit. Each profile has one descriptor vector followed by one vector per example brief.',
    model: EMBED_MODEL,
    dims: EMBED_DIMS,
    taskType: 'RETRIEVAL_DOCUMENT',
    builtAt: new Date().toISOString(),
    profiles: index
  })
  console.log(`Wrote ${INDEX_FILE}`)

  const evalBriefs = readJson(EVAL_BRIEFS_FILE, { briefs: [] }).briefs.map((b) => b.brief)
  console.log(`Embedding ${evalBriefs.length} eval briefs (RETRIEVAL_QUERY)...`)
  const evalVectors = await embedAll(evalBriefs, 'RETRIEVAL_QUERY')
  writeJson(EVAL_VECTORS_FILE, {
    _about: 'Generated by `npm run build-index`. Query embeddings of tests/eval/briefs.json so CI can score retrieval offline.',
    model: EMBED_MODEL,
    dims: EMBED_DIMS,
    taskType: 'RETRIEVAL_QUERY',
    briefs: Object.fromEntries(evalBriefs.map((brief, i) => [brief, evalVectors[i]]))
  })
  console.log(`Wrote ${EVAL_VECTORS_FILE}`)
}

const args = new Set(process.argv.slice(2))
const runBriefs = args.has('--briefs') || !args.has('--embed')
const runEmbed = args.has('--embed') || !args.has('--briefs')

try {
  if (runBriefs) await generateBriefs()
  if (runEmbed) await embed()
} catch (err) {
  console.error('build-index failed:', err.message)
  process.exit(1)
}
